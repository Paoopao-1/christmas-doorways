// “换一个方向”的轮换顺序：先同一画面的另一种讲法，再到其他画面
export function worldOrder(scene) {
  const ids = SCENES.map((s) => s.id);
  const rest = ids.filter((id) => id !== scene);
  return [scene, ...rest].flatMap((id) => [`${id}-a`, `${id}-b`]);
}

// 创建者只写了文字、没选画面时，按关键词推断
export function inferScene(text = '') {
  if (/雪|公寓|窗|楼|屋|家/.test(text)) return 'snow';
  if (/森林|树|林|山|鹿/.test(text)) return 'forest';
  if (/车|站|列车|火车|地铁|铁轨|信/.test(text)) return 'station';
  return 'secret';
}

export function buildWorld(key, d) {
  const w = WORLDS[key] || WORLDS['snow-a'];
  const anchors = w.anchors.map((text) => ({ text }));
  if (d.detail?.trim()) {
    anchors.splice(3, 0, { text: `「${d.detail.trim()}」——这件小事，会被悄悄藏进其中一扇门里。`, detail: true });
  }
  return {
    key,
    scene: w.scene,
    variant: w.variant,
    name: w.name(d.to.trim()),
    tagline: w.tagline,
    anchors,
    arc: w.arc,
    quote: d.sceneText?.trim() || '',
  };
}
